"""
generate_rules.py — Realistic IoT firewall rule generator.

Generates a production-scale ACL ruleset for the IoT VNF firewall.

Modeled after real-world IoT gateway firewall policies documented in:
  - NIST SP 800-213: IoT Device Cybersecurity Guidance
  - ETSI EN 303 645: Cyber Security for Consumer IoT
  - IEC 62443-3-3: Industrial Automation Security
  - Wool (2004): A quantitative study of firewall configuration errors

Design philosophy:
  The simulator generates ONLY valid, well-formed messages from known
  gateway IDs (gw-01 to gw-25) with correct sensor types and sfc_target
  values. This mirrors a real deployment where legitimate IoT traffic
  dominates (~95% allow rate).

  Rule categories serve different purposes:
    - Early rules (priority 1-11): block the small % of bad traffic fast
    - Zone/time/rate rules (20-50): enforce policy on known gateways
    - Explicit allowlist (60): cover all known gateway/sensor combos
    - Synthetic rules (60): cover unknown/future gateways — these NEVER
      fire for simulator traffic, they exist purely to simulate the
      lookup overhead of a large real-world ruleset
    - Default deny (999): catch-all for anything not explicitly allowed

  This gives ~95% allow rate on simulator traffic while maintaining
  a realistically large ruleset (500-10000 rules) for performance testing.

Usage:
    python generate_rules.py --output config/rules.json
    python generate_rules.py --output config/rules.json --profile small
    python generate_rules.py --output config/rules.json --profile large
"""

import argparse
import json
import random

# ── Sensor taxonomy ────────────────────────────────────────────────────────────

SENSOR_TYPES_SFC1 = [
    "temperature", "humidity", "co2",
    "vibration", "pressure", "power",
]

SENSOR_TYPES_SFC2 = [
    "packet_loss", "latency", "throughput",
]

ALL_SENSOR_TYPES = SENSOR_TYPES_SFC1 + SENSOR_TYPES_SFC2

# Real simulator gateway IDs (gw-01 to gw-25)
GATEWAY_IDS = [f"gw-{i:02d}" for i in range(1, 26)]

# Zone groupings — logical network segments
ZONES = {
    "campus_a":   [f"gw-{i:02d}" for i in range(1,  6)],
    "campus_b":   [f"gw-{i:02d}" for i in range(6,  11)],
    "factory_1":  [f"gw-{i:02d}" for i in range(11, 16)],
    "factory_2":  [f"gw-{i:02d}" for i in range(16, 21)],
    "datacenter": [f"gw-{i:02d}" for i in range(21, 26)],
}

# Explicitly blocked gateways (~12% of known gateways)
# In production: populated from threat intelligence feed
# In testbed: these gateway IDs are NOT generated by the simulator
# so blocking them has zero impact on throughput — they exist to
# demonstrate the firewall's threat blocking capability
BLOCKED_GATEWAYS = [f"gw-{i:02d}" for i in [3, 7, 14]]

# High-frequency gateways — rate limiting applies
# Again: rate limit is set high enough that simulator traffic never hits it
HIGH_FREQ_GATEWAYS = [f"gw-{i:02d}" for i in [1, 5, 10, 15, 20]]


def generate_infrastructure_rules() -> list:
    """
    Category 1: Infrastructure allow rules (priority 1-2).
    Control plane and monitoring traffic — always allowed first.
    Real firewalls put these at the top for performance.
    """
    return [
        {
            "comment":     "INFRA: Allow established connections (stateful tracking)",
            "rule_type":   "stateful",
            "ct_state":    "established",
            "action":      "ALLOW",
            "priority":    1,
        },
        {
            "comment":     "INFRA: Allow Prometheus scrape (monitoring system)",
            "rule_type":   "infrastructure",
            "src_gateway": "monitoring",
            "sensor_type": "*",
            "sfc_target":  "*",
            "action":      "ALLOW",
            "priority":    2,
        },
    ]


def generate_anomaly_block_rules() -> list:
    """
    Category 4: Explicit deny rules (priority 10-11).
    Block known-bad sources BEFORE allow rules are evaluated.
    These gateway IDs are NOT generated by the simulator —
    they exist to demonstrate threat blocking and have zero
    impact on simulator throughput.
    """
    rules = []

    # Block flagged gateways (threat intelligence)
    for gw in BLOCKED_GATEWAYS:
        rules.append({
            "comment":     f"THREAT: Block flagged gateway {gw} (threat intel feed)",
            "rule_type":   "threat_block",
            "src_gateway": gw,
            "sensor_type": "*",
            "sfc_target":  "*",
            "action":      "DENY",
            "priority":    10,
        })

    # Block protocol mismatches — defense against misconfigured sensors
    # Network sensors must ONLY go to sfc2
    for sensor_type in SENSOR_TYPES_SFC2:
        rules.append({
            "comment":     f"ANOMALY: Block {sensor_type} on SFC1 (wrong chain)",
            "rule_type":   "protocol_mismatch",
            "src_gateway": "*",
            "sensor_type": sensor_type,
            "sfc_target":  "sfc1",
            "action":      "DENY",
            "priority":    11,
        })

    # Environmental/industrial sensors must ONLY go to sfc1
    for sensor_type in SENSOR_TYPES_SFC1:
        rules.append({
            "comment":     f"ANOMALY: Block {sensor_type} on SFC2 (wrong chain)",
            "rule_type":   "protocol_mismatch",
            "src_gateway": "*",
            "sensor_type": sensor_type,
            "sfc_target":  "sfc2",
            "action":      "DENY",
            "priority":    11,
        })

    return rules


def generate_zone_rules() -> list:
    """
    Category 6: Zone-based allow rules (priority 20).
    Each zone explicitly allows its permitted sensor types.
    All known simulator gateways are covered here — this is
    where the bulk of simulator traffic matches and is allowed.
    """
    rules = []

    zone_policies = {
        "campus_a":   SENSOR_TYPES_SFC1,
        "campus_b":   SENSOR_TYPES_SFC1,
        "factory_1":  ["vibration", "pressure", "power"],
        "factory_2":  ["vibration", "pressure", "power"],
        "datacenter": SENSOR_TYPES_SFC2,
    }

    for zone, allowed_types in zone_policies.items():
        for gw in ZONES[zone]:
            if gw in BLOCKED_GATEWAYS:
                continue
            for sensor_type in allowed_types:
                sfc = "sfc1" if sensor_type in SENSOR_TYPES_SFC1 else "sfc2"
                rules.append({
                    "comment":     f"ZONE {zone}: ALLOW {gw} → {sensor_type} → {sfc}",
                    "rule_type":   "zone_policy",
                    "src_gateway": gw,
                    "sensor_type": sensor_type,
                    "sfc_target":  sfc,
                    "action":      "ALLOW",
                    "priority":    20,
                })

    return rules


def generate_time_window_rules() -> list:
    """
    Category 3: Time-window allow rules (priority 30).
    Industrial sensors allowed only during shift hours (06:00-22:00).
    Outside these hours the simulator uses night schedule (1 gateway)
    so very little industrial traffic is generated anyway.
    """
    rules = []

    for gw in ZONES["factory_1"] + ZONES["factory_2"]:
        if gw in BLOCKED_GATEWAYS:
            continue
        for sensor_type in ["vibration", "pressure", "power"]:
            # ALLOW during shift hours (06:00-22:00)
            rules.append({
                "comment":     f"TIME: ALLOW {gw} → {sensor_type} during shift (06-22)",
                "rule_type":   "time_window",
                "src_gateway": gw,
                "sensor_type": sensor_type,
                "sfc_target":  "sfc1",
                "time_start":  6,
                "time_end":    22,
                "action":      "ALLOW",
                "priority":    30,
            })
            # DENY outside shift hours (22:00-06:00)
            # This must come BEFORE explicit_allow rules at priority 60
            # so out-of-hours traffic is actually blocked
            rules.append({
                "comment":     f"TIME: DENY {gw} → {sensor_type} outside shift (22-06)",
                "rule_type":   "time_window_deny",
                "src_gateway": gw,
                "sensor_type": sensor_type,
                "sfc_target":  "sfc1",
                "time_start":  22,
                "time_end":    6,
                "action":      "DENY",
                "priority":    31,
            })

    return rules


def generate_rate_limit_rules() -> list:
    """
    Category 5: Rate-limit rules (priority 40).
    Rate limit is set to 10x the maximum simulator output per gateway
    so it NEVER fires during normal operation — it only fires if a
    real rogue device floods the system.
    Simulator peak: ~1200 msg/s per gateway at business peak.
    Rate limit: 10000 msg/s — 8x headroom.
    """
    rules = []

    for gw in HIGH_FREQ_GATEWAYS:
        for sensor_type in ALL_SENSOR_TYPES:
            sfc = "sfc1" if sensor_type in SENSOR_TYPES_SFC1 else "sfc2"
            rules.append({
                "comment":           f"RATE: ALLOW {gw} → {sensor_type} (limit 10000/s)",
                "rule_type":         "rate_limit",
                "src_gateway":       gw,
                "sensor_type":       sensor_type,
                "sfc_target":        sfc,
                "rate_limit_per_s":  10000,
                "action":            "ALLOW",
                "priority":          40,
            })

    return rules


def generate_protocol_validation_rules() -> list:
    """
    Category 7: Protocol validation — allow known sensor types (priority 50).
    Any message with a valid sensor type from any gateway passes.
    This is the safety net: if zone rules somehow don't match,
    this catches it and allows legitimate traffic.
    """
    rules = []

    for sensor_type in ALL_SENSOR_TYPES:
        sfc = "sfc1" if sensor_type in SENSOR_TYPES_SFC1 else "sfc2"
        rules.append({
            "comment":     f"PROTO: ALLOW known sensor type {sensor_type}",
            "rule_type":   "protocol_validation",
            "src_gateway": "*",
            "sensor_type": sensor_type,
            "sfc_target":  sfc,
            "action":      "ALLOW",
            "priority":    50,
        })

    return rules


def generate_explicit_gateway_rules() -> list:
    """
    Category 2: Explicit per-gateway allowlist (priority 60).
    Every known simulator gateway explicitly allowed for all
    its valid sensor types. Belt-and-suspenders approach.
    """
    rules = []

    for gw in GATEWAY_IDS:
        if gw in BLOCKED_GATEWAYS:
            continue
        for sensor_type in ALL_SENSOR_TYPES:
            sfc = "sfc1" if sensor_type in SENSOR_TYPES_SFC1 else "sfc2"
            rules.append({
                "comment":     f"EXPLICIT: ALLOW {gw} → {sensor_type} → {sfc}",
                "rule_type":   "explicit_allow",
                "src_gateway": gw,
                "sensor_type": sensor_type,
                "sfc_target":  sfc,
                "action":      "ALLOW",
                "priority":    60,
            })

    return rules


def generate_synthetic_rules(target_count: int, current_count: int) -> list:
    """
    Synthetic rules for unknown/future gateways (priority 60).

    These rules cover gateway IDs that the simulator NEVER generates
    (gw-0026 onwards). They exist ONLY to bring the total ruleset to
    a realistic size — simulating the lookup overhead of a large
    production firewall without affecting simulator traffic at all.

    All synthetic rules are ALLOW — there is no reason to deny future
    gateways preemptively, and making them ALLOW ensures they never
    accidentally impact performance measurement.
    """
    rules = []
    needed = max(0, target_count - current_count - 1)  # -1 for default deny

    # Generate synthetic gateway IDs well outside simulator range
    synthetic_gws = [f"gw-{i:04d}" for i in range(26, 26 + needed // len(ALL_SENSOR_TYPES) + 2)]

    for gw in synthetic_gws:
        if len(rules) >= needed:
            break
        for sensor_type in ALL_SENSOR_TYPES:
            if len(rules) >= needed:
                break
            sfc = "sfc1" if sensor_type in SENSOR_TYPES_SFC1 else "sfc2"
            rules.append({
                "comment":     f"SYNTHETIC: ALLOW {gw} → {sensor_type} (future gateway)",
                "rule_type":   "synthetic",
                "src_gateway": gw,
                "sensor_type": sensor_type,
                "sfc_target":  sfc,
                "action":      "ALLOW",
                "priority":    60,
            })

    return rules


def generate_ruleset(target_count: int = 1500) -> list:
    """
    Generate complete ordered firewall ruleset.
    Rules sorted by priority — lower number evaluated first.
    First matching rule wins (iptables/nftables semantics).
    """
    ruleset = []

    ruleset += generate_infrastructure_rules()       # priority 1-2
    ruleset += generate_anomaly_block_rules()        # priority 10-11
    ruleset += generate_zone_rules()                 # priority 20
    ruleset += generate_time_window_rules()          # priority 30
    ruleset += generate_rate_limit_rules()           # priority 40
    ruleset += generate_protocol_validation_rules()  # priority 50
    ruleset += generate_explicit_gateway_rules()     # priority 60

    # Fill to target count with synthetic rules
    ruleset += generate_synthetic_rules(
        target_count  = target_count,
        current_count = len(ruleset),
    )

    # Sort by priority
    ruleset.sort(key=lambda r: r.get("priority", 99))

    # Default deny — must be last
    ruleset.append({
        "comment":   "DEFAULT: Deny all — explicit allowlist model",
        "rule_type": "default",
        "action":    "DENY",
        "priority":  999,
    })

    return ruleset


def main():
    parser = argparse.ArgumentParser(
        description="Generate realistic IoT firewall ruleset"
    )
    parser.add_argument("--output",  default="config/rules.json")
    parser.add_argument(
        "--profile",
        choices=["small", "medium", "large"],
        default="medium",
        help="small=500, medium=1500, large=10000",
    )
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    profile_counts = {"small": 500, "medium": 1500, "large": 10000}
    count = profile_counts[args.profile]

    random.seed(args.seed)

    print(f"Generating {count} rules (profile: {args.profile})...")
    ruleset = generate_ruleset(target_count=count)

    import os
    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w") as f:
        json.dump(ruleset, f, indent=2)

    # Summary
    allow = sum(1 for r in ruleset if r.get("action") == "ALLOW")
    deny  = sum(1 for r in ruleset if r.get("action") == "DENY")
    type_counts = {}
    for r in ruleset:
        t = r.get("rule_type", "unknown")
        type_counts[t] = type_counts.get(t, 0) + 1

    print(f"\nGenerated {len(ruleset)} rules:")
    print(f"  ALLOW: {allow} ({allow/len(ruleset)*100:.1f}%)")
    print(f"  DENY:  {deny}  ({deny/len(ruleset)*100:.1f}%)")
    print(f"\nBy type:")
    for t, c in sorted(type_counts.items(), key=lambda x: -x[1]):
        print(f"  {t:35s}: {c}")
    print(f"\nNote: synthetic rules cover gw-0026+ (never generated by simulator)")
    print(f"      Simulator traffic (gw-01 to gw-25) hits zone/explicit rules")
    print(f"      and passes at ~95%+ rate.")
    print(f"\nWritten to: {args.output}")


if __name__ == "__main__":
    main()

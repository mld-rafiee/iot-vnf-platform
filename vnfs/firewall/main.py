"""
Firewall VNF — Entry point for SFC1 and SFC2.

Real-world implementation using nftables (Linux kernel firewall).
Ruleset generated by generate_rules.py — 500 to 10,000 rules
covering zone policies, threat blocks, time windows, rate limits,
protocol validation, and per-gateway allowlists.

References:
  - NIST SP 800-213: IoT Device Cybersecurity Guidance
  - ETSI EN 303 645: Cyber Security for Consumer IoT
  - IEC 62443-3-3: Industrial Automation Security
  - Wool (2004): A quantitative study of firewall configuration errors
"""

import json
import logging
import os
import subprocess
import tempfile
import threading
import time
from datetime import datetime
from typing import Optional

from base_vnf import BaseVNF
from metrics import VNFMetrics
from vnf_memory import VNFMemoryTracker

log = logging.getLogger(__name__)


class NFTablesFirewall:
    """
    Firewall engine backed by nftables.

    Loads rules from generate_rules.py output (rules.json).
    Evaluates each message against the ordered ruleset.
    First matching rule wins — same semantics as iptables/nftables.

    Rule types:
      stateful            — connection tracking (handled by nftables kernel)
      infrastructure      — always allow control plane traffic
      threat_block        — explicit deny for flagged sources
      protocol_mismatch   — deny sensor on wrong SFC chain
      zone_policy         — allow per zone policy
      time_window         — allow only during specified hours
      time_window_deny    — deny outside specified hours
      rate_limit          — allow with per-source rate enforcement
      protocol_validation — allow known sensor types
      explicit_allow      — per-gateway explicit allow
      synthetic           — large-scale rules (never fire for simulator)
      default             — catch-all deny
    """

    def __init__(self, rules_path: str):
        self._rules = []
        self._load_rules(rules_path)
        self._apply_nftables()

        # Rate tracking: key → [count, window_start_time]
        # Protected by lock — shared across worker threads within one process
        self._rate_tracker      = {}
        self._rate_tracker_lock = threading.Lock()

    def _load_rules(self, path: str):
        with open(path) as f:
            self._rules = json.load(f)
        log.info(f"Loaded {len(self._rules)} firewall rules from {path}")

    def _apply_nftables(self):
        """
        Apply nftables base ruleset for stateful connection tracking.
        Per-flow ACL is handled in Python since messages are JSON,
        not raw IP packets.
        """
        nft_script = """
table inet vnf_firewall {
    chain input {
        type filter hook input priority 0; policy accept;
        ct state established,related accept
        ct state invalid drop
    }
    chain forward {
        type filter hook forward priority 0; policy accept;
    }
}
"""
        try:
            with tempfile.NamedTemporaryFile(
                mode="w", suffix=".nft", delete=False
            ) as f:
                f.write(nft_script)
                tmp = f.name
            result = subprocess.run(
                ["nft", "-f", tmp],
                capture_output=True,
                text=True,
            )
            os.unlink(tmp)
            if result.returncode == 0:
                log.info("nftables stateful connection tracking applied")
            else:
                log.warning(
                    f"nftables not available: {result.stderr.strip()} "
                    f"— Python-only evaluation active"
                )
        except FileNotFoundError:
            log.warning(
                "nft binary not found — Python-only evaluation active. "
                "Install nftables package in production container."
            )

    def evaluate(
        self,
        src_gateway:   str,
        sensor_type:   str,
        sfc_target:    str,
        msg_timestamp: float,
    ) -> tuple:
        """
        Evaluate message against ruleset.
        Returns (action, rule_comment): ("ALLOW"|"DENY", str).

        Rules are pre-sorted by priority in generate_rules.py.
        First matching rule wins — identical to iptables/nftables semantics.
        """
        hour = datetime.fromtimestamp(msg_timestamp).hour

        for rule in self._rules:
            rule_type = rule.get("rule_type", "unknown")
            action    = rule.get("action",    "DENY")
            comment   = rule.get("comment",   "")

            # Stateful rules are handled by nftables kernel — skip in Python
            if rule_type == "stateful":
                continue

            # Default rule — matches everything, must be last
            if rule_type == "default":
                return action, comment

            # ── Field matching — "*" is wildcard ──────────────────────────
            r_gw     = rule.get("src_gateway", "*")
            r_sensor = rule.get("sensor_type", "*")
            r_sfc    = rule.get("sfc_target",  "*")

            if not (
                (r_gw     == "*" or r_gw     == src_gateway) and
                (r_sensor == "*" or r_sensor == sensor_type) and
                (r_sfc    == "*" or r_sfc    == sfc_target)
            ):
                continue  # Fields don't match — try next rule

            # ── Time window check ──────────────────────────────────────────
            if rule_type in ("time_window", "time_window_deny"):
                t_start  = rule.get("time_start", 0)
                t_end    = rule.get("time_end",   24)
                # Handle window that wraps midnight (e.g. 22:00-06:00)
                if t_start < t_end:
                    in_window = t_start <= hour < t_end
                else:
                    in_window = hour >= t_start or hour < t_end
                if not in_window:
                    continue  # This rule doesn't apply right now — next rule

            # ── Rate limit check ───────────────────────────────────────────
            if rule_type == "rate_limit":
                limit = rule.get("rate_limit_per_s", 10000)
                now   = time.time()
                key   = f"{src_gateway}:{sensor_type}"

                with self._rate_tracker_lock:
                    if key not in self._rate_tracker:
                        self._rate_tracker[key] = [0, now]

                    count, window_start = self._rate_tracker[key]

                    if now - window_start >= 1.0:
                        # New second — reset window
                        self._rate_tracker[key] = [1, now]
                    else:
                        # Same second — increment THEN check
                        count += 1
                        self._rate_tracker[key][0] = count
                        if count > limit:
                            return "DENY", f"RATE_EXCEEDED: {comment}"

            # Rule matched — return its action
            return action, comment

        # Fallthrough (should not reach here if default rule exists)
        return "DENY", "DEFAULT: fallthrough — no matching rule"


class FirewallVNF(BaseVNF):
    """
    Firewall VNF — entry point for one SFC chain.

    firewall-1 on worker-1: consumes sfc1-ingress → UDP → DPI
    firewall-2 on worker-2: consumes sfc2-ingress → UDP → DPI
    Same code, SFC_CHAIN env var selects which chain.
    """

    def __init__(
        self,
        vnf_name: str,
        config:   dict,
        metrics:  VNFMetrics,
        mem:      VNFMemoryTracker,
    ):
        super().__init__(vnf_name, config, metrics, mem)
        self._fw = NFTablesFirewall(config["firewall"]["rules_path"])
        log.info(f"[{vnf_name}] Firewall VNF ready")

    def get_flow_key(self, message: dict) -> tuple:
        """5-tuple flow key from message fields."""
        return (
            message.get("type",       "unknown"),   # protocol
            message.get("gateway_id", "unknown"),   # source
            message.get("sensor_id",  "unknown"),   # source port analog
            message.get("sfc_target", "unknown"),   # destination chain
            message.get("unit",       "unknown"),   # service
        )

    def process(self, message: dict) -> Optional[dict]:
        """
        Evaluate message against nftables ruleset.
        Returns message if ALLOW, None if DENY.
        """
        src_gateway   = message.get("gateway_id", "unknown")
        sensor_type   = message.get("type",        "unknown")
        sfc_target    = message.get("sfc_target",  "unknown")
        msg_timestamp = message.get("timestamp",   time.time())

        t_start = time.time()

        action, rule_comment = self._fw.evaluate(
            src_gateway   = src_gateway,
            sensor_type   = sensor_type,
            sfc_target    = sfc_target,
            msg_timestamp = msg_timestamp,
        )

        self.metrics.fw_rule_lookup_duration.labels(
            vnf=self.vnf_name
        ).observe(time.time() - t_start)

        if action == "DENY":
            self.metrics.fw_rules_blocked.labels(
                vnf=self.vnf_name
            ).inc()
            log.debug(
                f"[{self.vnf_name}] DENY {src_gateway}/{sensor_type} "
                f"→ {rule_comment}"
            )
            return None

        self.metrics.fw_rules_matched.labels(vnf=self.vnf_name).inc()
        self.metrics.fw_active_connections.labels(
            vnf=self.vnf_name
        ).set(self.mem.stats()["active_flows"])

        # Tag message as firewall-passed and record which rule matched
        message["fw_passed"]    = True
        message["fw_rule"]      = rule_comment
        message["fw_timestamp"] = time.time()

        return message


def build_config() -> dict:
    """Build config from environment variables (K8s ConfigMap/Secret)."""
    sfc_chain = os.environ.get("SFC_CHAIN", "sfc1")
    return {
        "kafka": {
            "bootstrap_servers": os.environ.get(
                "KAFKA_BOOTSTRAP_SERVERS",
                "iot-kafka-kafka-bootstrap.kafka.svc.cluster.local:9092",
            ),
        },
        "transport": {
            # Entry VNF — consume from Kafka ingress topic
            "kafka_input":        True,
            "kafka_input_topics": [f"{sfc_chain}-ingress"],
            # Forward to DPI on worker-3 via UDP
            "udp_output_host": os.environ.get("NEXT_HOP_HOST", "worker-3"),
            "udp_output_port": int(os.environ.get("NEXT_HOP_PORT", "9001")),
        },
        "firewall": {
            "rules_path": os.environ.get(
                "RULES_PATH", "/app/config/rules.json"
            ),
        },
    }


if __name__ == "__main__":
    config   = build_config()
    vnf_name = os.environ.get("VNF_NAME", "firewall-1")
    FirewallVNF.run(vnf_name=vnf_name, config=config)
